/**
 * Applied on open. Additive only: new kinds need no migration because every kind lives in
 * `doc`. STRICT tables reject type drift.
 */
export const SCHEMA_SQL = /* sql */ `
PRAGMA journal_mode = WAL;
PRAGMA synchronous = NORMAL;

-- Every synced document of every kind. body is the JSON of a doc that passed parseDoc(kind).
-- A delete keeps the row with body NULL (tombstone) and a new rev.
CREATE TABLE IF NOT EXISTS doc (
  kind       TEXT    NOT NULL,
  id         TEXT    NOT NULL,
  rev        INTEGER NOT NULL UNIQUE,   -- global write order; the UNIQUE index serves pulls and MAX(rev)
  body       TEXT,
  written_by TEXT    NOT NULL,          -- client id or 'server:health' (debugging only)
  written_at INTEGER NOT NULL,
  PRIMARY KEY (kind, id)
) STRICT;

-- Push idempotency. A mutation id at or below last_mutation_id has been processed.
CREATE TABLE IF NOT EXISTS client (
  id               TEXT    PRIMARY KEY,
  last_mutation_id INTEGER NOT NULL,
  first_seen_at    INTEGER NOT NULL,
  last_seen_at     INTEGER NOT NULL,
  user_agent       TEXT
) STRICT;

-- Refused mutations, kept for debugging. Never read by sync.
CREATE TABLE IF NOT EXISTS rejection (
  client_id   TEXT    NOT NULL,
  mutation_id INTEGER NOT NULL,
  at          INTEGER NOT NULL,
  reason      TEXT    NOT NULL,
  mutation    TEXT    NOT NULL,
  PRIMARY KEY (client_id, mutation_id)
) STRICT;

-- 'epoch': random, created with the database, regenerated by scripts/restore.sh.
CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT NOT NULL) STRICT;

-- Raw external responses. Server-owned, never synced, safe to delete at any time.
CREATE TABLE IF NOT EXISTS lookup_cache (
  source     TEXT    NOT NULL,          -- 'off' | 'usda'
  key        TEXT    NOT NULL,          -- gtin or fdcId
  fetched_at INTEGER NOT NULL,
  status     TEXT    NOT NULL CHECK (status IN ('found', 'not_found')),
  body       TEXT,
  PRIMARY KEY (source, key)
) STRICT;

-- Last 200 raw Shortcut payloads and their results, for debugging Shortcut builds.
CREATE TABLE IF NOT EXISTS ingest_log (
  seq    INTEGER PRIMARY KEY,
  at     INTEGER NOT NULL,
  body   TEXT    NOT NULL,
  result TEXT    NOT NULL
) STRICT;
`;

export type CacheHit = { readonly status: 'found'; readonly body: unknown } | { readonly status: 'not_found' };

export interface LookupCache {
  get(source: 'off' | 'usda', key: string, maxAgeMs: number, now: Millis): CacheHit | null;
  put(source: 'off' | 'usda', key: string, hit: CacheHit, now: Millis): void;
}

export interface DocStore {
  /**
   * One round trip of the sync protocol, in one IMMEDIATE transaction:
   *
   *   last = client.last_mutation_id (0 for a new client)
   *   for m in req.mutations (ascending id) where m.id > last:
   *     reason = check(m)   // KindName, writer === 'client', parseDoc(kind, doc), doc.id === docId
   *     if reason: insert rejection
   *     else: upsert doc(kind, id) with body = JSON(doc) or NULL, rev = MAX(rev) + 1
   *     last = m.id
   *   update client.last_mutation_id = last
   *   from = req.epoch === epoch ? req.cursor : 0
   *   changes = SELECT ... WHERE rev > from ORDER BY rev LIMIT 1001  (more = 1001 rows)
   *   rejected[i].current = the doc row after the batch, or null
   *
   * Replaying the same request is a no-op for the push half, so a lost response is safe to
   * retry. The driver is synchronous and the process is single-threaded, so transactions
   * never interleave and rev order equals commit order: a pull never skips a rev that
   * commits later.
   */
  sync(req: SyncRequest, now: Millis, userAgent: string | null): SyncResponse;

  /**
   * The only write path for server-owned kinds (Health). merge receives the current doc or
   * null and returns the next doc; a result equal to the current doc (canonical JSON) is
   * 'unchanged' and does not bump rev, so hourly Shortcut resends do not churn phone syncs.
   */
  writeServerDoc<K extends ServerKind>(
    kind: K,
    id: string,
    merge: (current: DocOf<K> | null) => DocOf<K>,
    now: Millis,
  ): 'stored' | 'unchanged';

  /** Non-archived library foods, for AI name matching. Reads the same rows the phone has. */
  libraryFoods(): Food[];

  readonly cache: LookupCache;

  /** Appends to ingest_log and trims it to 200 rows. */
  logIngest(body: string, result: string, now: Millis): void;

  /**
   * Online backup (better-sqlite3 backup API) to <dir>/.fuel-<date>.db.tmp, then rename to
   * fuel-<date>.db and delete all but the newest `keep`. Re-running on the same day replaces
   * that day's file; a crash leaves only a .tmp the next run overwrites.
   */
  backup(dir: string, today: LocalDate, keep: number): Promise<string>;

  stats(): { epoch: string; rev: Rev; dbBytes: number };
  close(): void;
}

